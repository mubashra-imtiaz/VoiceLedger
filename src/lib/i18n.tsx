export type Key = keyof typeof dict.en;

type Ctx = { lang: Lang; t: (k: Key) => string; setLang: (l: Lang) => void };
const I18nCtx = createContext<Ctx>({ lang: "en", t: (k) => dict.en[k], setLang: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = (typeof window !== "undefined" && (localStorage.getItem("vl_lang") as Lang)) || "en";
    setLangState(saved);
  }, []);
  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", lang === "ur" ? "rtl" : "ltr");
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("vl_lang", l);
  };
  const t = (k: Key) => (dict[lang][k] ?? dict.en[k]) as string;
  return <I18nCtx.Provider value={{ lang, t, setLang }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
